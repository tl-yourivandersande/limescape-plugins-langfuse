"""Copy the fase A checks from the evals repository into their node type.

The checks are maintained in the evals repository (fase-a/evaluators.py, the output contract
and the conversion from the Limescape agent's output). A plugin bundle is built from this
repository alone, so the node type carries a generated copy. This script makes that copy:

    python scripts/sync_fase_a_checks.py <path to juridische-adviseur-evals>
    python scripts/sync_fase_a_checks.py <path> --check    # exit 1 when the copy is out of date

Only two things differ from the source: the import of ``Evaluation`` (the node has its own,
so the bundle does not need the Langfuse SDK) and, for the conversion, the selection of the
definitions that do not call the Limescape API. Never edit the generated files by hand.
"""

from __future__ import annotations

import argparse
import ast
import hashlib
import subprocess  # noqa: S404 - git only, fixed arguments
import sys
from pathlib import Path

TARGET = Path(__file__).resolve().parents[1] / "src" / "node-types" / "juridische_adviseur_fase_a"
SDK_IMPORT = "from langfuse import Evaluation\n"
OWN_IMPORT = "from ._evaluation import Evaluation\n"
# From fase-a/limescape/dossier_analyse.py: everything naar_contract needs, nothing that calls the API.
CONTRACT_DEFINITIONS = ("SLEUTEL", "ONBEKEND", "_leeg_is_none", "naar_contract")
HEADER = (
    "# GENERATED by scripts/sync_fase_a_checks.py from {source} in the evals repository.\n"
    "# Do not edit: change the source and run the script again.\n"
)


def _git(repo: Path, *arguments: str) -> str:
    command = ["git", *arguments]
    return subprocess.run(command, cwd=repo, capture_output=True, text=True, check=True).stdout.strip()  # noqa: S603


def _evaluators(source: str) -> str:
    if source.count(SDK_IMPORT) != 1:
        raise SystemExit("fase-a/evaluators.py no longer has exactly one 'from langfuse import Evaluation'")
    return HEADER.format(source="fase-a/evaluators.py") + source.replace(SDK_IMPORT, OWN_IMPORT)


def _contract(source: str) -> str:
    tree = ast.parse(source)
    found: dict[str, str] = {}
    for node in tree.body:
        if isinstance(node, ast.FunctionDef):
            names = [node.name]
        elif isinstance(node, ast.Assign):
            names = [target.id for target in node.targets if isinstance(target, ast.Name)]
        else:
            continue
        for name in names:
            if name in CONTRACT_DEFINITIONS:
                # Leading comments belong to the definition; take the lines above it up to a blank line.
                lines = source.splitlines()
                start = node.lineno - 1
                while start > 0 and lines[start - 1].lstrip().startswith("#"):
                    start -= 1
                found[name] = "\n".join(lines[start : node.end_lineno])
    missing = [name for name in CONTRACT_DEFINITIONS if name not in found]
    if missing:
        raise SystemExit(f"fase-a/limescape/dossier_analyse.py no longer defines: {', '.join(missing)}")
    body = "\n\n\n".join(found[name] for name in CONTRACT_DEFINITIONS)
    return (
        HEADER.format(source="fase-a/limescape/dossier_analyse.py")
        + '"""Zet de uitkomst van de Limescape-agent om naar het uitvoercontract van fase A."""\n\n'
        + "import re\n\n"
        + body
        + "\n"
    )


def generate(evals: Path) -> dict[str, str]:
    fase_a = evals / "fase-a"
    evaluators = (fase_a / "evaluators.py").read_text(encoding="utf-8")
    contract_json = (fase_a / "uitvoercontract.json").read_text(encoding="utf-8")
    # The same fingerprint fase-a/experiment.py puts on a run, so runs from the flow and from the
    # script can be compared on evaluator version.
    fingerprint = hashlib.sha256()
    for name in ("evaluators.py", "uitvoercontract.json"):
        fingerprint.update((fase_a / name).read_bytes())
    commit = _git(evals, "rev-parse", "--short", "HEAD")
    paths = ("fase-a/evaluators.py", "fase-a/uitvoercontract.json", "fase-a/limescape/dossier_analyse.py")
    if _git(evals, "status", "--porcelain", "--", *paths):
        commit += "-dirty"
    version = (
        HEADER.format(source="fase-a")
        + '"""Welke stand van de controles deze node bevat."""\n\n'
        + f'SOURCE_COMMIT = "{commit}"\n'
        + f'EVALUATOR_VERSION = "{fingerprint.hexdigest()[:12]}"\n'
    )
    return {
        "_evaluators.py": _evaluators(evaluators),
        "_contract.py": _contract((fase_a / "limescape" / "dossier_analyse.py").read_text(encoding="utf-8")),
        "_version.py": version,
        "uitvoercontract.json": contract_json,
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("evals", type=Path, help="checkout of the juridische-adviseur-evals repository")
    parser.add_argument("--check", action="store_true", help="only compare; exit 1 when the copy is out of date")
    arguments = parser.parse_args()

    files = generate(arguments.evals.resolve())
    stale = [
        name
        for name, content in files.items()
        if not (TARGET / name).is_file() or (TARGET / name).read_text(encoding="utf-8") != content
    ]
    if arguments.check:
        if stale:
            sys.exit("out of date: " + ", ".join(stale))
        print("the fase A checks are up to date")
        return
    TARGET.mkdir(parents=True, exist_ok=True)
    for name in stale:
        (TARGET / name).write_text(content := files[name], encoding="utf-8")
        print(f"written {name} ({len(content.splitlines())} lines)")
    if not stale:
        print("nothing changed")


if __name__ == "__main__":
    main()
